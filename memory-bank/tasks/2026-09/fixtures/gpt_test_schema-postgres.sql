-- Glass Power Tools — Stage 3 database test fixture (PostgreSQL 18)
-- Logical twin of gpt_test_schema-mysql.sql. Deterministic: fixed ids, fixed timestamps.
-- Run as a provisioning superuser against the gpt_test database. Contains no credentials.

DROP TABLE IF EXISTS members;
DROP TABLE IF EXISTS teams;

CREATE TABLE teams (
    id          INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(64)     NOT NULL,
    active      BOOLEAN         NOT NULL,
    budget      NUMERIC(12,2)   NOT NULL,
    created_at  TIMESTAMP       NOT NULL,
    notes       TEXT            NULL,
    PRIMARY KEY (id),
    CONSTRAINT teams_name_key UNIQUE (name)
);

CREATE TABLE members (
    id          INTEGER         GENERATED BY DEFAULT AS IDENTITY,
    team_id     INTEGER         NOT NULL,
    full_name   VARCHAR(128)    NOT NULL,
    email       VARCHAR(128)    NULL,
    is_lead     BOOLEAN         NOT NULL,
    hourly_rate NUMERIC(8,2)    NULL,
    joined_at   TIMESTAMP       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT members_team_id_fkey FOREIGN KEY (team_id) REFERENCES teams (id)
);

CREATE INDEX members_team_id_idx ON members (team_id);

