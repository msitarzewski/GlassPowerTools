import Foundation

/// X11 keysyms (RFC 6143 §7.5.4) for the RDP set-1 scancodes that every glassDT input surface
/// already produces, so VNC sessions reuse the existing keyboard handling unchanged.
/// Reference: X11 keysymdef.h, https://gitlab.freedesktop.org/xorg/proto/xorgproto/-/blob/master/include/X11/keysymdef.h
public enum RFBKeysym {
    public static let backspace: UInt32 = 0xFF08, tab: UInt32 = 0xFF09, `return`: UInt32 = 0xFF0D, escape: UInt32 = 0xFF1B
    public static let delete: UInt32 = 0xFFFF, capsLock: UInt32 = 0xFFE5, numLock: UInt32 = 0xFF7F, scrollLock: UInt32 = 0xFF14
    public static let shiftLeft: UInt32 = 0xFFE1, shiftRight: UInt32 = 0xFFE2, controlLeft: UInt32 = 0xFFE3, controlRight: UInt32 = 0xFFE4
    public static let altLeft: UInt32 = 0xFFE9, altRight: UInt32 = 0xFFEA, superLeft: UInt32 = 0xFFEB, superRight: UInt32 = 0xFFEC
    public static let menu: UInt32 = 0xFF67

    private static let base: [UInt16: UInt32] = [
        0x01: escape, 0x02: 0x31, 0x03: 0x32, 0x04: 0x33, 0x05: 0x34, 0x06: 0x35, 0x07: 0x36, 0x08: 0x37, 0x09: 0x38,
        0x0A: 0x39, 0x0B: 0x30, 0x0C: 0x2D, 0x0D: 0x3D, 0x0E: backspace, 0x0F: tab,
        0x10: 0x71, 0x11: 0x77, 0x12: 0x65, 0x13: 0x72, 0x14: 0x74, 0x15: 0x79, 0x16: 0x75, 0x17: 0x69, 0x18: 0x6F, 0x19: 0x70,
        0x1A: 0x5B, 0x1B: 0x5D, 0x1C: `return`, 0x1D: controlLeft,
        0x1E: 0x61, 0x1F: 0x73, 0x20: 0x64, 0x21: 0x66, 0x22: 0x67, 0x23: 0x68, 0x24: 0x6A, 0x25: 0x6B, 0x26: 0x6C,
        0x27: 0x3B, 0x28: 0x27, 0x29: 0x60, 0x2A: shiftLeft, 0x2B: 0x5C,
        0x2C: 0x7A, 0x2D: 0x78, 0x2E: 0x63, 0x2F: 0x76, 0x30: 0x62, 0x31: 0x6E, 0x32: 0x6D, 0x33: 0x2C, 0x34: 0x2E, 0x35: 0x2F,
        0x36: shiftRight, 0x37: 0xFFAA, 0x38: altLeft, 0x39: 0x20, 0x3A: capsLock,
        0x3B: 0xFFBE, 0x3C: 0xFFBF, 0x3D: 0xFFC0, 0x3E: 0xFFC1, 0x3F: 0xFFC2, 0x40: 0xFFC3, 0x41: 0xFFC4, 0x42: 0xFFC5,
        0x43: 0xFFC6, 0x44: 0xFFC7, 0x45: numLock, 0x46: scrollLock,
        0x47: 0xFF95, 0x48: 0xFF97, 0x49: 0xFF9A, 0x4A: 0xFFAD, 0x4B: 0xFF96, 0x4C: 0xFF9D, 0x4D: 0xFF98, 0x4E: 0xFFAB,
        0x4F: 0xFF9C, 0x50: 0xFF99, 0x51: 0xFF9B, 0x52: 0xFF9E, 0x53: 0xFF9F,
        0x56: 0x3C, 0x57: 0xFFC8, 0x58: 0xFFC9, 0x5D: menu
    ]

    private static let extended: [UInt16: UInt32] = [
        0x1C: 0xFF8D, 0x1D: controlRight, 0x35: 0xFFAF, 0x38: altRight, 0x47: 0xFF50, 0x48: 0xFF52, 0x49: 0xFF55,
        0x4B: 0xFF51, 0x4D: 0xFF53, 0x4F: 0xFF57, 0x50: 0xFF54, 0x51: 0xFF56, 0x52: 0xFF63, 0x53: delete,
        0x5B: superLeft, 0x5C: superRight, 0x5D: menu
    ]

    public static func keysym(scancode: UInt16, extended isExtended: Bool) -> UInt32? {
        isExtended ? extended[scancode] : base[scancode]
    }

    /// Latin-1 scalars are their own keysyms; everything else uses the Unicode keysym range.
    public static func keysym(for scalar: Unicode.Scalar) -> UInt32? {
        switch scalar.value {
        case 0x0A, 0x0D: return `return`
        case 0x09: return tab
        case 0x08: return backspace
        case 0x1B: return escape
        case 0x7F: return delete
        case 0x20...0x7E, 0xA0...0xFF: return scalar.value
        case 0x100...0x10FFFF: return 0x0100_0000 + scalar.value
        default: return nil
        }
    }
}
